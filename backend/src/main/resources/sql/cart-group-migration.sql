-- Cart group migration for existing oneulFarm databases
-- Run this script once on the current schema before using grouped recipe cart features.

CREATE TABLE OFT_CART_GROUP (
    CART_GROUP_NO NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    CART_NO NUMBER(19) NOT NULL,
    GROUP_KEY VARCHAR2(120) NOT NULL,
    GROUP_TYPE VARCHAR2(20) NOT NULL,
    RECIPE_NO NUMBER(19),
    GROUP_NAME VARCHAR2(100),
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_OFT_CART_GROUP PRIMARY KEY (CART_GROUP_NO),
    CONSTRAINT FK_OFT_CG_CART FOREIGN KEY (CART_NO) REFERENCES OFT_CART (CART_NO),
    CONSTRAINT FK_OFT_CG_RECIPE FOREIGN KEY (RECIPE_NO) REFERENCES OFT_RECIPE (RECIPE_NO),
    CONSTRAINT UQ_OFT_CG_CART_KEY UNIQUE (CART_NO, GROUP_KEY),
    CONSTRAINT CK_OFT_CG_TYPE CHECK (GROUP_TYPE IN ('PRODUCT', 'RECIPE'))
);

INSERT INTO OFT_CART_GROUP (
    CART_NO,
    GROUP_KEY,
    GROUP_TYPE,
    RECIPE_NO,
    GROUP_NAME,
    CREATED_AT,
    UPDATED_AT
)
SELECT
    ci.CART_NO,
    'PRODUCT:' || TO_CHAR(ci.PRODUCT_NO) AS GROUP_KEY,
    'PRODUCT' AS GROUP_TYPE,
    NULL AS RECIPE_NO,
    MAX(p.PRODUCT_NAME) AS GROUP_NAME,
    MIN(ci.CREATED_AT) AS CREATED_AT,
    MAX(ci.UPDATED_AT) AS UPDATED_AT
FROM OFT_CART_ITEM ci
JOIN OFT_PRODUCT p
    ON p.PRODUCT_NO = ci.PRODUCT_NO
GROUP BY ci.CART_NO, ci.PRODUCT_NO;

ALTER TABLE OFT_CART_ITEM ADD (
    CART_GROUP_NO NUMBER(19)
);

UPDATE OFT_CART_ITEM ci
SET CART_GROUP_NO = (
    SELECT cg.CART_GROUP_NO
    FROM OFT_CART_GROUP cg
    WHERE cg.CART_NO = ci.CART_NO
      AND cg.GROUP_KEY = 'PRODUCT:' || TO_CHAR(ci.PRODUCT_NO)
)
WHERE ci.CART_GROUP_NO IS NULL;

ALTER TABLE OFT_CART_ITEM MODIFY (
    CART_GROUP_NO NUMBER(19) NOT NULL
);

ALTER TABLE OFT_CART_ITEM DROP CONSTRAINT UQ_OFT_CI_CART_PROD;

ALTER TABLE OFT_CART_ITEM
ADD CONSTRAINT FK_OFT_CI_GROUP FOREIGN KEY (CART_GROUP_NO) REFERENCES OFT_CART_GROUP (CART_GROUP_NO);

ALTER TABLE OFT_CART_ITEM
ADD CONSTRAINT UQ_OFT_CI_GROUP_PROD UNIQUE (CART_GROUP_NO, PRODUCT_NO);

CREATE OR REPLACE TRIGGER TRG_OFT_CGROUP_UPD_AT
BEFORE UPDATE ON OFT_CART_GROUP FOR EACH ROW
BEGIN
    :NEW.UPDATED_AT := SYSTIMESTAMP;
END;
