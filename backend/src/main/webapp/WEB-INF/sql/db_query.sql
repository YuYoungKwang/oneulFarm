-- 3. PRODUCT
CREATE TABLE OFT_PRODUCT (
    PRODUCT_NO NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    CATEGORY_NO NUMBER(19) NOT NULL,
    PRODUCT_NAME VARCHAR2(100) NOT NULL,
    ORIGIN VARCHAR2(100),
    UNIT VARCHAR2(20) NOT NULL,
    PACKAGE_WEIGHT NUMBER(10,2) DEFAULT 0 NOT NULL,
    SALE_PRICE NUMBER(10,2) DEFAULT 0 NOT NULL,
    STOCK_QTY NUMBER(10) DEFAULT 0 NOT NULL,
