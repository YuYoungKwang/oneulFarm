        (DELIVERY_STATUS = 'READY' AND SHIPPED_AT IS NULL AND DELIVERED_AT IS NULL)
        OR
        (DELIVERY_STATUS = 'SHIPPING' AND SHIPPED_AT IS NOT NULL AND DELIVERED_AT IS NULL)
        OR
        (DELIVERY_STATUS = 'DELIVERED' AND SHIPPED_AT IS NOT NULL AND DELIVERED_AT IS NOT NULL AND DELIVERED_AT >= SHIPPED_AT)
    )
);


