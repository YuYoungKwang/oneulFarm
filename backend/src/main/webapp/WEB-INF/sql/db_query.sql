    CONSTRAINT CK_OFT_PROD_SPRICE CHECK (SALE_PRICE >= 0),
    CONSTRAINT CK_OFT_PROD_STOCK CHECK (STOCK_QTY >= 0),
    CONSTRAINT CK_OFT_PROD_SEASON CHECK (IS_SEASONAL IN ('Y', 'N')),
    CONSTRAINT CK_OFT_PROD_STATUS CHECK (SALE_STATUS IN ('READY', 'SELLING', 'SOLD_OUT', 'STOP'))
);

CREATE INDEX IX_OFT_PRODUCT_CAT ON OFT_PRODUCT (CATEGORY_NO);


