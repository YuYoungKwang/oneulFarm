INSERT INTO OFT_PRODUCT_PRICE_MATCH (
    PRODUCT_NO, SNAPSHOT_NO, COMPARED_PRICE, PRICE_GAP, SAVING_RATE, BADGE_TYPE
)
SELECT
    p.PRODUCT_NO,
    latest_price.SNAPSHOT_NO,
    p.SALE_PRICE,
    CASE
        WHEN latest_price.AVG_PRICE - p.SALE_PRICE >= 100 THEN ROUND(latest_price.AVG_PRICE - p.SALE_PRICE, 2)
        ELSE 0
    END AS PRICE_GAP,
    CASE
        WHEN latest_price.AVG_PRICE - p.SALE_PRICE >= 100
             AND latest_price.AVG_PRICE > 0
        THEN ROUND(((latest_price.AVG_PRICE - p.SALE_PRICE) / latest_price.AVG_PRICE) * 100, 2)
        ELSE 0
    END AS SAVING_RATE,
    CASE
        WHEN latest_price.AVG_PRICE - p.SALE_PRICE >= 100 THEN 'UNDER_AVG'
        ELSE NULL
    END AS BADGE_TYPE
FROM OFT_PRODUCT p
JOIN OFT_PRODUCT_PRICE_CODE_MAP pcm
  ON pcm.PRODUCT_NO = p.PRODUCT_NO
 AND pcm.IS_ACTIVE = 'Y'
JOIN (
    SELECT
        SNAPSHOT_NO,
        ITEM_CODE,
        MARKET_TYPE,
        AVG_PRICE
    FROM (
        SELECT
            ps.SNAPSHOT_NO,
            ps.ITEM_CODE,
            ps.MARKET_TYPE,
            ps.AVG_PRICE,
            ROW_NUMBER() OVER (
                PARTITION BY ps.ITEM_CODE, ps.MARKET_TYPE
                ORDER BY ps.SNAPSHOT_DATE DESC, ps.SNAPSHOT_NO DESC
            ) AS RN
        FROM OFT_PRICE_SNAPSHOT ps
    )
    WHERE RN = 1
) latest_price
  ON latest_price.MARKET_TYPE = pcm.MARKET_TYPE
 AND latest_price.ITEM_CODE =
        pcm.MARKET_TYPE || '_' ||
        pcm.ITEM_CATEGORY_CODE || '_' ||
        pcm.ITEM_CODE || '_' ||
        REPLACE(TRIM(pcm.KIND_CODE), '|', '-') || '_' ||
        pcm.PRODUCT_RANK_CODE || '_' ||
        pcm.COUNTRY_CODE || '_' ||
        pcm.CONVERT_KG_YN
WHERE p.DESCRIPTION LIKE '[DUMMY] 2026-03 시세 연동 상품%';

