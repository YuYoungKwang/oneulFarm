/* =========================================================
   3. PRODUCT
   ========================================================= */
CREATE TABLE PRODUCT (
    PRODUCT_NO NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    CATEGORY_NO NUMBER(19) NOT NULL,
    PRODUCT_NAME VARCHAR2(100) NOT NULL,
    ORIGIN VARCHAR2(100),
