/* =========================================================
   1. USERS
   ========================================================= */
CREATE TABLE USERS (
    USER_NO NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    USER_ID VARCHAR2(50) NOT NULL,
    EMAIL VARCHAR2(100) NOT NULL,
    PASSWORD VARCHAR2(255) NOT NULL,
    NICKNAME VARCHAR2(50) NOT NULL,
    PHONE VARCHAR2(20) NOT NULL,
    ROLE VARCHAR2(20) DEFAULT 'USER' NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    DELETED_AT TIMESTAMP,
    PROFILE_IMAGE_URL VARCHAR2(500),
    PROFILE_IMAGE_NAME VARCHAR2(255),
    PROFILE_IMAGE_EXT VARCHAR2(20),
    PROFILE_IMAGE_MIME_TYPE VARCHAR2(100),
    PROFILE_IMAGE_SIZE NUMBER(10),
    PROFILE_IMAGE_DATA BLOB,
    CONSTRAINT PK_USERS PRIMARY KEY (USER_NO),
    CONSTRAINT CK_USERS_ROLE CHECK (ROLE IN ('USER', 'ADMIN')),
    CONSTRAINT CK_USERS_STATUS CHECK (STATUS IN ('ACTIVE', 'WITHDRAWN', 'BLOCKED')),
    CONSTRAINT CK_USERS_UID_TRIM CHECK (USER_ID = TRIM(USER_ID)),
    CONSTRAINT CK_USERS_EML_TRIM CHECK (EMAIL = TRIM(EMAIL)),
    CONSTRAINT CK_USERS_NICK_TRIM CHECK (NICKNAME = TRIM(NICKNAME)),
    CONSTRAINT CK_USERS_PIMG_SIZE CHECK (PROFILE_IMAGE_SIZE IS NULL OR PROFILE_IMAGE_SIZE >= 0)
);

CREATE UNIQUE INDEX UX_USERS_UID_CI
    ON USERS (UPPER(TRIM(USER_ID)));

CREATE UNIQUE INDEX UX_USERS_EMAIL_CI
    ON USERS (UPPER(TRIM(EMAIL)));

CREATE UNIQUE INDEX UX_USERS_NICK_CI
    ON USERS (UPPER(TRIM(NICKNAME)));


