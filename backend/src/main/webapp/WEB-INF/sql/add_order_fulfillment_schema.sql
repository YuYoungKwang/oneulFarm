USING (
    SELECT 'CJ' AS CARRIER_CODE, 'CJ LOGISTICS' AS CARRIER_NAME, 'https://trace.example.com/cj/{trackingNo}' AS TRACKING_URL_TEMPLATE FROM DUAL
) source
ON (target.CARRIER_CODE = source.CARRIER_CODE)
WHEN MATCHED THEN UPDATE SET
    target.CARRIER_NAME = source.CARRIER_NAME,
    target.TRACKING_URL_TEMPLATE = source.TRACKING_URL_TEMPLATE,
