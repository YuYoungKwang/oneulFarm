/* ---------------------------------------------------------
   1. USERS ROLE EXTENSION
   --------------------------------------------------------- */

-- Existing role check:
-- CK_OFT_USERS_ROLE CHECK (ROLE IN ('USER', 'ADMIN'))
-- Extend it so carrier accounts can log in to a dedicated carrier page.
ALTER TABLE OFT_USERS DROP CONSTRAINT CK_OFT_USERS_ROLE;

ALTER TABLE OFT_USERS
ADD CONSTRAINT CK_OFT_USERS_ROLE
CHECK (ROLE IN ('USER', 'ADMIN', 'CARRIER'));


/* ---------------------------------------------------------
   2. CARRIER MASTER
   --------------------------------------------------------- */

CREATE TABLE OFT_CARRIER (
    CARRIER_CODE VARCHAR2(30) NOT NULL,
    CARRIER_NAME VARCHAR2(100) NOT NULL,
    TRACKING_URL_TEMPLATE VARCHAR2(500),
    STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_OFT_CARRIER PRIMARY KEY (CARRIER_CODE),
    CONSTRAINT CK_OFT_CARRIER_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE')),
    CONSTRAINT CK_OFT_CARRIER_CODE_TRIM CHECK (CARRIER_CODE = TRIM(CARRIER_CODE)),
    CONSTRAINT CK_OFT_CARRIER_NAME_TRIM CHECK (CARRIER_NAME = TRIM(CARRIER_NAME))
);

CREATE UNIQUE INDEX UX_OFT_CARRIER_NAME_CI
ON OFT_CARRIER (UPPER(TRIM(CARRIER_NAME)));


/* ---------------------------------------------------------
   3. CARRIER USER MAPPING
   --------------------------------------------------------- */

CREATE TABLE OFT_CARRIER_USER (
    CARRIER_USER_NO NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    USER_NO NUMBER(19) NOT NULL,
    CARRIER_CODE VARCHAR2(30) NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_OFT_CARRIER_USER PRIMARY KEY (CARRIER_USER_NO),
    CONSTRAINT FK_OFT_CUSER_USER FOREIGN KEY (USER_NO) REFERENCES OFT_USERS (USER_NO),
    CONSTRAINT FK_OFT_CUSER_CARRIER FOREIGN KEY (CARRIER_CODE) REFERENCES OFT_CARRIER (CARRIER_CODE),
    CONSTRAINT UQ_OFT_CUSER_USER UNIQUE (USER_NO),
    CONSTRAINT CK_OFT_CUSER_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE'))
);

CREATE INDEX IX_OFT_CUSER_CARRIER ON OFT_CARRIER_USER (CARRIER_CODE);


/* ---------------------------------------------------------
   4. ORDERS EXTENSION
   --------------------------------------------------------- */

-- Current ORDER_STATUS uses business states mixed with shipping/cancel semantics.
-- New design separates:
--   ORDER_STATUS
--   CANCEL_STATUS
--   PURCHASE_CONFIRM_STATUS

ALTER TABLE OFT_ORDERS ADD (
    CANCEL_STATUS VARCHAR2(30) DEFAULT 'NONE' NOT NULL,
    PURCHASE_CONFIRM_STATUS VARCHAR2(30) DEFAULT 'PURCHASE_PENDING' NOT NULL,
    PURCHASE_CONFIRMED_AT TIMESTAMP
);

ALTER TABLE OFT_ORDERS DROP CONSTRAINT CK_OFT_ORD_STATUS;

ALTER TABLE OFT_ORDERS
ADD CONSTRAINT CK_OFT_ORD_STATUS
CHECK (ORDER_STATUS IN ('PAYMENT_COMPLETED', 'ORDER_ACCEPTED', 'ORDER_REJECTED'));

ALTER TABLE OFT_ORDERS
ADD CONSTRAINT CK_OFT_ORD_CANCEL_STATUS
CHECK (CANCEL_STATUS IN ('NONE', 'CANCEL_REQUESTED', 'CANCEL_ACCEPTED', 'CANCEL_REJECTED'));

ALTER TABLE OFT_ORDERS
ADD CONSTRAINT CK_OFT_ORD_PURCHASE_CONFIRM
CHECK (PURCHASE_CONFIRM_STATUS IN ('PURCHASE_PENDING', 'PURCHASE_CONFIRMED'));

CREATE INDEX IX_OFT_ORD_STATUS ON OFT_ORDERS (ORDER_STATUS);
CREATE INDEX IX_OFT_ORD_CANCEL_STATUS ON OFT_ORDERS (CANCEL_STATUS);


/* ---------------------------------------------------------
   5. DELIVERY EXTENSION
   --------------------------------------------------------- */

-- Existing OFT_DELIVERY has:
--   COURIER_NAME, TRACKING_NO, DELIVERY_STATUS, SHIPPED_AT, DELIVERED_AT
-- Extend it to support carrier entity + richer milestones.

ALTER TABLE OFT_DELIVERY ADD (
    CARRIER_CODE VARCHAR2(30),
    WAYBILL_STATUS VARCHAR2(30) DEFAULT 'NOT_ASSIGNED' NOT NULL,
    WAYBILL_ASSIGNED_AT TIMESTAMP,
    PICKED_UP_AT TIMESTAMP,
    IN_TRANSIT_AT TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

ALTER TABLE OFT_DELIVERY DROP CONSTRAINT CK_OFT_DEL_STATUS;

ALTER TABLE OFT_DELIVERY
ADD CONSTRAINT CK_OFT_DEL_STATUS
CHECK (DELIVERY_STATUS IN ('NOT_STARTED', 'WAYBILL_ASSIGNED', 'PICKED_UP', 'IN_TRANSIT', 'DELIVERED'));

ALTER TABLE OFT_DELIVERY
ADD CONSTRAINT CK_OFT_DEL_WAYBILL_STATUS
CHECK (WAYBILL_STATUS IN ('NOT_ASSIGNED', 'ASSIGNED'));

ALTER TABLE OFT_DELIVERY
ADD CONSTRAINT FK_OFT_DEL_CARRIER
FOREIGN KEY (CARRIER_CODE) REFERENCES OFT_CARRIER (CARRIER_CODE);

ALTER TABLE OFT_DELIVERY DROP CONSTRAINT UQ_OFT_DEL_TRACK;

ALTER TABLE OFT_DELIVERY
ADD CONSTRAINT UQ_OFT_DEL_CARRIER_TRACK UNIQUE (CARRIER_CODE, TRACKING_NO);

CREATE INDEX IX_OFT_DEL_CARRIER ON OFT_DELIVERY (CARRIER_CODE);
CREATE INDEX IX_OFT_DEL_STATUS ON OFT_DELIVERY (DELIVERY_STATUS);


/* ---------------------------------------------------------
   6. ORDER STATUS HISTORY
   --------------------------------------------------------- */

CREATE TABLE OFT_ORDER_STATUS_HISTORY (
    ORDER_STATUS_HISTORY_NO NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ORDER_NO NUMBER(19) NOT NULL,
    PREV_ORDER_STATUS VARCHAR2(30),
    NEXT_ORDER_STATUS VARCHAR2(30) NOT NULL,
    CHANGED_BY_TYPE VARCHAR2(20) NOT NULL,
    CHANGED_BY_USER_NO NUMBER(19),
    CHANGE_REASON VARCHAR2(500),
    CHANGED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_OFT_ORD_STATUS_HIS PRIMARY KEY (ORDER_STATUS_HISTORY_NO),
    CONSTRAINT FK_OFT_ORDSH_ORDER FOREIGN KEY (ORDER_NO) REFERENCES OFT_ORDERS (ORDER_NO),
    CONSTRAINT FK_OFT_ORDSH_USER FOREIGN KEY (CHANGED_BY_USER_NO) REFERENCES OFT_USERS (USER_NO),
    CONSTRAINT CK_OFT_ORDSH_NEXT CHECK (NEXT_ORDER_STATUS IN ('PAYMENT_COMPLETED', 'ORDER_ACCEPTED', 'ORDER_REJECTED')),
    CONSTRAINT CK_OFT_ORDSH_ACTOR CHECK (CHANGED_BY_TYPE IN ('SYSTEM', 'ADMIN', 'CARRIER'))
);

CREATE INDEX IX_OFT_ORDSH_ORDER ON OFT_ORDER_STATUS_HISTORY (ORDER_NO, CHANGED_AT DESC);


/* ---------------------------------------------------------
   7. ORDER CANCEL REQUEST
   --------------------------------------------------------- */

CREATE TABLE OFT_ORDER_CANCEL_REQUEST (
    CANCEL_REQUEST_NO NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ORDER_NO NUMBER(19) NOT NULL,
    REQUESTED_BY_USER_NO NUMBER(19) NOT NULL,
    CANCEL_STATUS VARCHAR2(30) DEFAULT 'CANCEL_REQUESTED' NOT NULL,
    REQUEST_REASON VARCHAR2(500),
    DECISION_REASON VARCHAR2(500),
    DECIDED_BY_USER_NO NUMBER(19),
    REQUESTED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    DECIDED_AT TIMESTAMP,
    CONSTRAINT PK_OFT_ORD_CANCEL_REQ PRIMARY KEY (CANCEL_REQUEST_NO),
    CONSTRAINT FK_OFT_OCR_ORDER FOREIGN KEY (ORDER_NO) REFERENCES OFT_ORDERS (ORDER_NO),
    CONSTRAINT FK_OFT_OCR_REQ_USER FOREIGN KEY (REQUESTED_BY_USER_NO) REFERENCES OFT_USERS (USER_NO),
    CONSTRAINT FK_OFT_OCR_DEC_USER FOREIGN KEY (DECIDED_BY_USER_NO) REFERENCES OFT_USERS (USER_NO),
    CONSTRAINT CK_OFT_OCR_STATUS CHECK (CANCEL_STATUS IN ('CANCEL_REQUESTED', 'CANCEL_ACCEPTED', 'CANCEL_REJECTED'))
);

CREATE INDEX IX_OFT_OCR_ORDER ON OFT_ORDER_CANCEL_REQUEST (ORDER_NO, REQUESTED_AT DESC);


/* ---------------------------------------------------------
   8. DELIVERY TRACKING HISTORY
   --------------------------------------------------------- */

CREATE TABLE OFT_DELIVERY_TRACKING_HISTORY (
    TRACKING_HISTORY_NO NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ORDER_NO NUMBER(19) NOT NULL,
    DELIVERY_NO NUMBER(19) NOT NULL,
    CARRIER_CODE VARCHAR2(30) NOT NULL,
    TRACKING_NO VARCHAR2(100),
    TRACKING_STATUS VARCHAR2(30) NOT NULL,
    TRACKING_MESSAGE VARCHAR2(500),
    RECORDED_BY_USER_NO NUMBER(19),
    RECORDED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_OFT_DEL_TRACK_HIS PRIMARY KEY (TRACKING_HISTORY_NO),
    CONSTRAINT FK_OFT_DTH_ORDER FOREIGN KEY (ORDER_NO) REFERENCES OFT_ORDERS (ORDER_NO),
    CONSTRAINT FK_OFT_DTH_DELIVERY FOREIGN KEY (DELIVERY_NO) REFERENCES OFT_DELIVERY (DELIVERY_NO),
    CONSTRAINT FK_OFT_DTH_CARRIER FOREIGN KEY (CARRIER_CODE) REFERENCES OFT_CARRIER (CARRIER_CODE),
    CONSTRAINT FK_OFT_DTH_USER FOREIGN KEY (RECORDED_BY_USER_NO) REFERENCES OFT_USERS (USER_NO),
    CONSTRAINT CK_OFT_DTH_STATUS CHECK (TRACKING_STATUS IN ('WAYBILL_ASSIGNED', 'PICKED_UP', 'IN_TRANSIT', 'DELIVERED'))
);

CREATE INDEX IX_OFT_DTH_ORDER ON OFT_DELIVERY_TRACKING_HISTORY (ORDER_NO, RECORDED_AT DESC);
CREATE INDEX IX_OFT_DTH_TRACK ON OFT_DELIVERY_TRACKING_HISTORY (CARRIER_CODE, TRACKING_NO, RECORDED_AT DESC);


