CREATE TABLE OFT_USER_SOCIAL_ACCOUNT (
    SOCIAL_ACCOUNT_NO NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    USER_NO NUMBER(19) NOT NULL,
    PROVIDER VARCHAR2(20) NOT NULL,
    PROVIDER_USER_ID VARCHAR2(100) NOT NULL,
    PROVIDER_EMAIL VARCHAR2(100),
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_OFT_USER_SOCIAL_ACCOUNT PRIMARY KEY (SOCIAL_ACCOUNT_NO),
    CONSTRAINT FK_OFT_SOCIAL_USER FOREIGN KEY (USER_NO) REFERENCES OFT_USERS (USER_NO),
    CONSTRAINT CK_OFT_SOCIAL_PROVIDER CHECK (PROVIDER IN ('KAKAO', 'NAVER', 'GOOGLE')),
    CONSTRAINT CK_OFT_SOCIAL_PROVIDER_TRIM CHECK (PROVIDER = TRIM(PROVIDER)),
    CONSTRAINT CK_OFT_SOCIAL_PROVIDER_UID_TRIM CHECK (PROVIDER_USER_ID = TRIM(PROVIDER_USER_ID))
);

CREATE UNIQUE INDEX UX_OFT_SOCIAL_PROVIDER_UID ON OFT_USER_SOCIAL_ACCOUNT (PROVIDER, PROVIDER_USER_ID);
CREATE INDEX IX_OFT_SOCIAL_USER_NO ON OFT_USER_SOCIAL_ACCOUNT (USER_NO);
